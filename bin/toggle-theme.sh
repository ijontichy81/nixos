#!/usr/bin/env bash

# 1. Toggle Caelestia Scheme
if caelestia scheme get -m | grep -q dark; then
    caelestia scheme set -m light
    # Update GTK apps
    sed -i 's/gtk-application-prefer-dark-theme=1/gtk-application-prefer-dark-theme=0/' ~/.config/gtk-3.0/settings.ini ~/.config/gtk-4.0/settings.ini
else
    caelestia scheme set -m dark
    sed -i 's/gtk-application-prefer-dark-theme=0/gtk-application-prefer-dark-theme=1/' ~/.config/gtk-3.0/settings.ini ~/.config/gtk-4.0/settings.ini
fi

# 2. Generate Btop dynamic theme file based on Caelestia colors
mkdir -p ~/.config/btop/themes
cat << BTOP_THEME > ~/.config/btop/themes/dynamic.theme
# Btop Dynamic Theme generated by toggle-theme.sh
theme[main_bg] = "$(caelestia scheme get | grep 'base:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[main_fg] = "$(caelestia scheme get | grep 'text:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[title] = "$(caelestia scheme get | grep 'text:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[hi_fg] = "$(caelestia scheme get | grep 'primary:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[selected_bg] = "$(caelestia scheme get | grep 'surfaceContainer:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[selected_fg] = "$(caelestia scheme get | grep 'onPrimaryContainer:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[inactive_fg] = "$(caelestia scheme get | grep 'subtext0:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[graph_text] = "$(caelestia scheme get | grep 'subtext1:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[proc_misc] = "$(caelestia scheme get | grep 'secondary:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[cpu_box] = "$(caelestia scheme get | grep 'primary:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[mem_box] = "$(caelestia scheme get | grep 'tertiary:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
theme[net_box] = "$(caelestia scheme get | grep 'secondary:' | sed -n 's/.*m\([0-9a-fA-F]\{6\}\).*/\1/p')"
BTOP_THEME

# 3. Point Btop to the new dynamic theme
sed -i 's/^color_theme = .*/color_theme = "dynamic.theme"/' ~/.config/btop/btop.conf

# 4. Reload UI components
pkill nautilus
